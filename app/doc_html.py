from __future__ import annotations
"""Standalone, print-ready HTML for the four documents plus an index.html cover (FR-14 add-on).

Each file is self-contained (inline CSS, inline SVG wireframes, no fonts or scripts from outside) so
「브라우저로 열기 → 인쇄 → PDF 저장」 gives an A4 document with page numbers, a cover block, a table of
contents and tables whose header row repeats on every page. The Markdown files stay as they are.
"""

import re
from collections.abc import Mapping, Sequence
from html import escape
from pathlib import Path
from typing import Any

PRINT_CSS = (Path(__file__).resolve().parent / "data" / "doc_print.css").read_text(encoding="utf-8")
DOC_PLAIN = {"brd": "왜 만드는지 — 문제와 목표", "prd": "무엇을 만드는지 — 요구사항",
             "screens": "어떻게 보이는지 — 화면", "tests": "다 됐는지 확인하는 법"}
DOC_NAMES = {"brd": "BRD", "prd": "PRD", "screens": "화면설계서", "tests": "테스트 케이스"}
MARKS = ("가정", "미결", "미확인")
_ID = re.compile(r"\b(?:SRC|REQ|SCR|TC|EV|DEC|OPEN|CF|Q|FND|PROTO)-\d+\b")
# A section starts a new printed page when it is long enough to deserve one (a screen sheet, a big table).
PAGE_ROWS = 6


def text(value: Any) -> str:
    """Escaped text with every ID wrapped as a chip."""
    return _ID.sub(lambda m: f'<span class="id">{m.group(0)}</span>', escape(str(value)))


def _status(value: str) -> str:
    v = value.strip()
    if v in MARKS:
        return f'<span class="badge warn">{escape(v)}</span>'
    if v == "확정":
        return f'<span class="badge ok">{escape(v)}</span>'
    return text(value)


def table_html(block: Mapping[str, Any]) -> str:
    columns: Sequence[str] = block["columns"]
    if not block["rows"]:
        return '<p class="empty">항목이 없습니다</p>'
    status = columns.index("상태") if "상태" in columns[1:] else -1
    head = "".join(f'<th scope="col">{escape(str(c))}</th>' for c in columns)
    rows = []
    for row in block["rows"]:
        marked = status >= 0 and str(row[status]).strip() in MARKS
        cells = "".join(f"<td>{_status(str(c)) if j == status else text(c)}</td>" for j, c in enumerate(row))
        rows.append(('<tr class="marked">' if marked else "<tr>") + f"{cells}</tr>")
    wide = ' class="wide"' if len(columns) > 7 else ""
    return f'<div class="table-wrap"><table{wide}><thead><tr>{head}</tr></thead><tbody>{"".join(rows)}</tbody></table></div>'


def block_html(block: Mapping[str, Any]) -> str:
    kind = block["type"]
    if kind == "table":
        return table_html(block)
    if kind == "paragraph":
        return f"<p>{text(block['text'])}</p>"
    if kind == "list":
        return "<ul>" + "".join(f"<li>{text(i)}</li>" for i in block["items"]) + "</ul>"
    if kind == "screen":
        # The wireframe SVG is generated by app/wireframe.py with every text XML-escaped.
        purpose = f'<p class="purpose">목적: {text(block["purpose"])}</p>' if block.get("purpose") else ""
        return (f'<div class="screen"><div class="wire" role="img" aria-label="{escape(block["title"])} 와이어프레임">'
                f'{block["svg"]}</div>{purpose}{table_html(block["elements"])}{table_html(block["states"])}</div>')
    raise ValueError(f"unknown block type: {kind}")


def _long(sec: Mapping[str, Any]) -> bool:
    for b in sec["blocks"]:
        if b["type"] == "screen" or (b["type"] == "table" and len(b["rows"]) > PAGE_ROWS):
            return True
    return False


def _date(iso: Any) -> str:
    m = re.match(r"(\d{4})-(\d{2})-(\d{2})", str(iso or ""))
    return f"{m[1]}. {int(m[2])}. {int(m[3])}." if m else "—"


def meta_html(header: Mapping[str, Any]) -> str:
    approvals = header.get("approvals") or []
    last = approvals[-1] if approvals else None
    if last and last.get("version") == header["version"]:
        state = f'<span class="badge ok">승인됨 · {escape(str(last["cp"]))} · {escape(str(last["who"]))}</span>'
    else:
        state = '<span class="badge warn">승인 전</span>'
    facts = (("버전", f'<span class="badge plain">{escape(str(header["version"]))}</span>'), ("승인", state),
             ("작성", escape(str(header["owner_name"]))), ("날짜", _date(last.get("at") if last else None)))
    return '<dl class="meta">' + "".join(f"<div><dt>{k}</dt><dd>{v}</dd></div>" for k, v in facts) + "</dl>"


def marked_html(marked: Mapping[str, Sequence[str]]) -> str:
    items = [(status, item) for status, values in marked.items() for item in values]
    if not items:
        return ""
    lis = "".join(f'<li><span class="badge warn">{escape(s)}</span> {text(i)}</li>' for s, i in items)
    return ('<aside class="callout" aria-label="확정되지 않은 항목"><h2>아직 확정되지 않은 항목 '
            f"{len(items)}건</h2><p>발주사가 확정하지 않았습니다. 그대로 만들기 전에 확인하세요.</p><ul>{lis}</ul></aside>")


def page(title: str, body: str, running_head: str) -> str:
    # Inside <style> entities are not decoded: drop what could close the style element (a project name, review 11-21)
    safe = running_head.replace("\\", "").replace('"', "'").replace("<", "").replace(">", "")
    head_css = '@page{@top-right{content:"' + safe + \
        '";font-size:9pt;color:#5f6677}}'
    return ('<!doctype html><html lang="ko"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            f"<title>{escape(title)}</title><style>{PRINT_CSS}{head_css}</style></head>"
            f'<body><main class="sheet">{body}</main></body></html>')


def doc_page(doc: Mapping[str, Any], marked: Mapping[str, Sequence[str]], project: str, at: str) -> str:
    doc_id = str(doc["id"])
    name = DOC_NAMES.get(doc_id, str(doc["title"]))
    toc = "".join(f'<li><a href="#{escape(s["id"])}">{text(s["title"])}</a></li>' for s in doc["sections"])
    summary = "".join(f"<li>{text(line)}</li>" for line in (doc.get("summary") or ["아직 요약이 없습니다"]))
    sections = "".join(
        f'<section class="part{" page" if _long(s) else ""}" id="{escape(s["id"])}" aria-labelledby="h-{escape(s["id"])}">'
        f'<h2 id="h-{escape(s["id"])}">{text(s["title"])}</h2>{"".join(block_html(b) for b in s["blocks"])}</section>'
        for s in doc["sections"])
    warnings = doc.get("warnings") or []
    warn_html = ("" if not warnings else
                 f'<section class="part" id="warnings"><h2>검사 경고 ({len(warnings)})</h2><ul class="warnings">'
                 + "".join(f"<li>{text(w['target'])} — {text(w['message'])}</li>" for w in warnings) + "</ul></section>")
    cover = (f'<div class="cover"><p class="kicker">{escape(project)}</p><h1 class="doc-title">{escape(name)}</h1>'
             f'<p class="doc-plain">{escape(DOC_PLAIN.get(doc_id, ""))}</p>{meta_html(doc["header"])}'
             f'{marked_html(marked)}<section class="summary" aria-label="한눈에 보기"><h2>한눈에 보기</h2>'
             f'<ul>{summary}</ul></section><nav class="toc" aria-label="목차"><h2>목차</h2><ol>{toc}</ol></nav></div>')
    foot = f'<p class="foot">0to1(영일)이 공유 원본에서 만든 문서 · 만든 시각(UTC) {escape(at)} · 데이터는 모두 가짜입니다</p>'
    return page(f"{name} — {project}", cover + sections + warn_html + foot,
                f"{name} {doc['header']['version']} · {project}")


def index_page(docs: Mapping[str, Mapping[str, Any]], files: Mapping[str, str], marked: Mapping[str, Sequence[str]],
               project: str, at: str, has_flow: bool) -> str:
    cards = "".join(f'<li><a href="{escape(files[d])}"><strong>{escape(DOC_NAMES[d])}</strong>'
                    f'<span>{escape(DOC_PLAIN[d])} · {escape(str(docs[d]["header"]["version"]))}</span></a></li>'
                    for d in files)
    extra = [("prototype.html", "웹 프로토타입", "브라우저로 열어 눌러 보는 화면")]
    if has_flow:
        extra.append(("user_flow.html", "사용자 흐름도", "화면 순서를 그린 그림"))
    cards += "".join(f'<li><a href="{f}"><strong>{t}</strong><span>{s}</span></a></li>' for f, t, s in extra)
    header = next(iter(docs.values()))["header"] if docs else {"version": "—", "owner_name": "—", "approvals": []}
    counts = " · ".join(f"{k} {len(v)}건" for k, v in marked.items())
    body = (f'<div class="cover"><p class="kicker">0to1(영일) — 결과물 묶음</p><h1 class="cover-title">{escape(project)}</h1>'
            f'<p class="cover-sub">문서 4종과 프로토타입 · 가정·미결 {escape(counts)}</p>{meta_html(header)}'
            f'<ul class="docs">{cards}</ul>{marked_html(marked)}</div>'
            f'<p class="foot">만든 시각(UTC) {escape(at)} · 각 문서는 브라우저 인쇄(A4)로 PDF 를 만들 수 있습니다</p>')
    return page(f"{project} — 결과물 묶음", body, project)


def html_documents(docs: Mapping[str, Mapping[str, Any]], doc_files: Mapping[str, str],
                   marked: Mapping[str, Sequence[str]], project: str, at: str, has_flow: bool = False,
                   per_doc: Mapping[str, Mapping[str, Sequence[str]]] | None = None) -> dict[str, str]:
    """{zip path: html} for every document (named like its Markdown file) plus index.html.
    `per_doc` gives each document its own unconfirmed items (the cover page keeps them all)."""
    files = {doc_id: name.rsplit(".", 1)[0] + ".html" for doc_id, name in doc_files.items() if doc_id in docs}
    out = {files[d]: doc_page(docs[d], marked if per_doc is None else per_doc.get(d, marked), project, at) for d in files}
    out["index.html"] = index_page(docs, files, marked, project, at, has_flow)
    return out
